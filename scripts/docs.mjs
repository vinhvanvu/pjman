// npm run docs: write docs/reference.md's command section from the CLI's own declaration (src/cli/surface.ts), between
// its markers, so the reference and `pjman --help` never drift. A test refuses a reference that is behind.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { referenceMarkdown } from '../dist/cli/surface.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'docs', 'reference.md');
const START = '<!-- commands: generated by npm run docs from src/cli/surface.ts -->';
const END = '<!-- /commands -->';
const doc = fs.readFileSync(file, 'utf8');
const a = doc.indexOf(START);
const b = doc.indexOf(END);
if (a < 0 || b < a) throw new Error(`docs/reference.md has no ${START} … ${END} block`);
const next = `${doc.slice(0, a)}${START}\n\n${referenceMarkdown()}\n\n${doc.slice(b)}`;
if (next !== doc) {
  fs.writeFileSync(file, next);
  console.log('docs/reference.md: the command section rewritten');
} else console.log('docs/reference.md: already in step');
